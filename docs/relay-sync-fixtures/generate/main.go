package main

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/hkdf"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
)

var b64 = base64.RawURLEncoding

func derive(secret []byte, info string) []byte {
	k, err := hkdf.Key(sha256.New, secret, nil, info, 32)
	if err != nil {
		panic(err)
	}
	return k
}

func kid(authKey []byte) string { s := sha256.Sum256(authKey); return b64.EncodeToString(s[:]) }

func seal(key []byte, kind byte, prefix []byte, chunk uint32, context string, pt []byte) []byte {
	hdr := []byte("MIR1")
	hdr = append(hdr, kind)
	hdr = append(hdr, prefix...)
	hdr = binary.BigEndian.AppendUint32(hdr, chunk)
	block, _ := aes.NewCipher(key)
	gcm, _ := cipher.NewGCM(block)
	out := append([]byte{}, hdr...)
	var chunks [][]byte
	for i := 0; i < len(pt); i += int(chunk) {
		end := min(i+int(chunk), len(pt))
		chunks = append(chunks, pt[i:end])
	}
	if len(pt)%int(chunk) == 0 {
		chunks = append(chunks, []byte{})
	}
	for i, c := range chunks {
		nonce := binary.BigEndian.AppendUint32(append([]byte{}, prefix...), uint32(i))
		final := byte(0)
		if i == len(chunks)-1 {
			final = 1
		}
		aad := append([]byte{}, hdr...)
		aad = binary.BigEndian.AppendUint32(aad, uint32(i))
		aad = append(aad, final)
		aad = append(aad, []byte(context)...)
		out = append(out, gcm.Seal(nil, nonce, c, aad)...)
	}
	return out
}

func sign(authKey []byte, method, path string, ts int64, body []byte) string {
	bh := sha256.Sum256(body)
	canon := fmt.Sprintf("MIR1\n%s\n%s\n%d\n%s", method, path, ts, hex.EncodeToString(bh[:]))
	m := hmac.New(sha256.New, authKey)
	m.Write([]byte(canon))
	return b64.EncodeToString(m.Sum(nil))
}

func seq(n int, start byte) []byte { b := make([]byte, n); for i := range b { b[i] = start + byte(i) }; return b }

