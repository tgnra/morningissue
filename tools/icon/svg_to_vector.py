#!/usr/bin/env python3
"""Writes the launcher icon's foreground vector drawable from the master SVG.

    python3 tools/icon/svg_to_vector.py          rewrite the drawable
    python3 tools/icon/svg_to_vector.py --check  fail if the drawable is out of date

The master is design/icon/morning-issue-icon.svg; the drawable is
app/src/main/res/drawable/ic_launcher_foreground.xml, used as both the foreground and
the monochrome layer of the adaptive icon. The path with id "ground" is left out: the
app's background layer is the colour ic_launcher_background.

Android vector drawables take only part of SVG, so the master is held to that part:
<path> elements with a plain fill or stroke on a 108 by 108 canvas. Anything else
(shapes, groups, transforms, styles, gradients, text) stops the script, rather than
letting the two drift apart unnoticed. It needs only Python's standard library.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MASTER = ROOT / "design/icon/morning-issue-icon.svg"
DRAWABLE = ROOT / "app/src/main/res/drawable/ic_launcher_foreground.xml"

SVG = "{http://www.w3.org/2000/svg}"
CANVAS = "0 0 108 108"
GROUND_ID = "ground"

# SVG attribute -> (drawable attribute, conversion)
COLOUR = re.compile(r"#[0-9A-Fa-f]{6}$")
NUMBER = re.compile(r"\d+(\.\d+)?$")


def colour(value):
    if not COLOUR.match(value):
        raise ValueError(f"colour must be #RRGGBB, not {value!r}")
    return value.upper()


def number(value):
    if not NUMBER.match(value):
        raise ValueError(f"expected a plain number, not {value!r}")
    return value


def one_of(**names):
    def convert(value):
        if value not in names:
            raise ValueError(f"expected one of {sorted(names)}, not {value!r}")
        return names[value]
    return convert


ATTRIBUTES = {
    "fill": ("fillColor", colour),
    "fill-rule": ("fillType", one_of(evenodd="evenOdd", nonzero="nonZero")),
    "stroke": ("strokeColor", colour),
    "stroke-width": ("strokeWidth", number),
    "stroke-linecap": ("strokeLineCap", one_of(butt="butt", round="round", square="square")),
    "stroke-linejoin": ("strokeLineJoin", one_of(miter="miter", round="round", bevel="bevel")),
}


def convert(svg_text):
    svg = ET.fromstring(svg_text)
    if svg.tag != SVG + "svg" or svg.get("viewBox") != CANVAS:
        raise ValueError(f'the master must be an <svg> with viewBox="{CANVAS}"')

    paths = []
    for element in svg:
        if element.tag != SVG + "path":
            raise ValueError(f"only <path> is allowed, found <{element.tag.replace(SVG, '')}>")
        name = element.get("id")
        if name == GROUND_ID:
            continue
        lines = [f'        android:name="{name}"'] if name else []
        for key, value in element.attrib.items():
            if key in ("id", "d"):
                continue
            if key == "fill" and value == "none":
                continue  # a drawable path has no fill unless given one
            if key not in ATTRIBUTES:
                raise ValueError(f"path {name!r}: attribute {key!r} has no drawable equivalent")
            drawable_key, conversion = ATTRIBUTES[key]
            try:
                lines.append(f'        android:{drawable_key}="{conversion(value)}"')
            except ValueError as error:
                raise ValueError(f"path {name!r}, {key}: {error}") from None
        if "fill" not in element.attrib:
            raise ValueError(f'path {name!r}: state the fill (SVG fills black by default); use fill="none" for lines')
        data = " ".join(element.get("d", "").split())
        if not data:
            raise ValueError(f"path {name!r} has no d")
        lines.append(f'        android:pathData="{data}"')
        paths.append("    <path\n" + "\n".join(lines) + " />\n")

    if not paths:
        raise ValueError("the master has no artwork")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Written by tools/icon/svg_to_vector.py from design/icon/morning-issue-icon.svg.\n"
        "     Change the SVG and run the script again; do not edit this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        + "".join(paths)
        + "</vector>\n"
    )


def main():
    try:
        drawable = convert(MASTER.read_text(encoding="utf-8"))
    except (ValueError, ET.ParseError) as error:
        sys.exit(f"{MASTER.relative_to(ROOT)}: {error}")
    if "--check" in sys.argv[1:]:
        current = DRAWABLE.read_text(encoding="utf-8") if DRAWABLE.exists() else ""
        if current != drawable:
            sys.exit(f"{DRAWABLE.relative_to(ROOT)} is out of date: run tools/icon/svg_to_vector.py")
        print("The drawable matches the master SVG.")
    else:
        DRAWABLE.write_text(drawable, encoding="utf-8")
        print(f"Wrote {DRAWABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
